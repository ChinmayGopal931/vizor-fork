#!/usr/bin/env python3
"""Append new entries to the Railgun page's Ethereum mainnet block-time table.

The Railgun page dates the records it reads from Anon's archive by this table:
the archive's own timestamps are wrong in long stretches, and the page never
asks an RPC for the time of a block it learned from the wallet's own notes.
Entry `i` is the header time of block `START_BLOCK + i * STEP`.

The table is append-only. Each run fetches blocks past the last entry, up to
`head - REORG_MARGIN`, from two independent RPC endpoints and requires them to
agree. It also re-reads the last existing entries and aborts if either endpoint
disagrees with the checked-in value. Nothing is written on any failure.

Usage:
  scripts/update-railgun-block-times.py            # fetch and append
  scripts/update-railgun-block-times.py --check    # validate the file offline

Exit status is 0 when the table is current or was updated, and 1 on any
failure.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = REPO_ROOT / "android/railgun-web/src/block-times-mainnet.js"

# Just before Railgun's first mainnet event, at block 14,751,290.
START_BLOCK = 14_750_000
STEP = 1_000
# Average spacing between consecutive entries must stay within these bounds:
# about 13 s under proof of work, 12 s slots since the Merge.
MIN_AVG_BLOCK_SECONDS = 10
MAX_AVG_BLOCK_SECONDS = 20
# Entries stay this many blocks below the lower endpoint head: two epochs,
# past which a block is final.
REORG_MARGIN = 64
# Existing entries re-read from both endpoints on every update.
RECHECK_EXISTING = 3
# Both serve blocks from before the Merge, which publicnode no longer keeps.
DEFAULT_ENDPOINTS = ("https://rpc.mevblocker.io", "https://ethereum.public.blockpi.network/v1/rpc/public")
# Calls per JSON-RPC batch, by host (free plans refuse larger batches), and
# batches in flight per endpoint.
BATCH = {"rpc.mevblocker.io": 50, "ethereum.public.blockpi.network": 5, "eth.drpc.org": 3}
DEFAULT_BATCH = 3
WORKERS = 1
RPC_TIMEOUT_SECONDS = 30
RPC_ATTEMPTS = 7
USER_AGENT = "railgun-block-times"

HEADER = """\
// @generated by scripts/update-railgun-block-times.py. Do not edit by hand.
//
// Header time of Ethereum mainnet block `START + i * STEP` for each entry `i`. A
// weekly workflow appends entries after two independent RPC endpoints agree on
// each value.
"""

TIMES_PATTERN = re.compile(r"export const TIMES = \[(?P<body>[^\]]*)\];", re.S)
CONST_PATTERN = re.compile(r"export const (START|STEP) = ([0-9_]+);")


class UpdateError(Exception):
    pass


def read_table() -> list[int]:
    if not DATA_FILE.exists():
        return []
    text = DATA_FILE.read_text()
    consts = {name: int(value.replace("_", "")) for name, value in CONST_PATTERN.findall(text)}
    if consts != {"START": START_BLOCK, "STEP": STEP}:
        raise UpdateError(f"{DATA_FILE} has unexpected constants: {consts}")
    match = TIMES_PATTERN.search(text)
    if match is None:
        raise UpdateError(f"{DATA_FILE} has no TIMES array")
    return [int(token) for token in re.findall(r"[0-9]+", match.group("body"))]


def render_table(times: list[int]) -> str:
    lines = [HEADER]
    lines.append(f"export const START = {START_BLOCK:_};")
    lines.append(f"export const STEP = {STEP:_};")
    lines.append("")
    lines.append("// prettier-ignore")
    lines.append("export const TIMES = [")
    for offset in range(0, len(times), 8):
        chunk = ", ".join(str(value) for value in times[offset : offset + 8])
        lines.append(f"  {chunk},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def block_at(index: int) -> int:
    return START_BLOCK + index * STEP


def validate(times: list[int], now: int) -> None:
    if not times:
        raise UpdateError("table is empty")
    for index in range(1, len(times)):
        previous, current = times[index - 1], times[index]
        average = (current - previous) / STEP
        if not MIN_AVG_BLOCK_SECONDS <= average <= MAX_AVG_BLOCK_SECONDS:
            raise UpdateError(
                f"average block interval {average:.1f}s before block {block_at(index)} "
                f"is outside {MIN_AVG_BLOCK_SECONDS}-{MAX_AVG_BLOCK_SECONDS}s"
            )
    if times[-1] > now:
        raise UpdateError(f"last entry {times[-1]} is in the future")


def rpc(endpoint: str, calls: list[tuple[str, list]]) -> list:
    """One JSON-RPC batch; the results in call order."""
    body = json.dumps(
        [{"jsonrpc": "2.0", "id": i, "method": method, "params": params} for i, (method, params) in enumerate(calls)]
    ).encode()
    last_error = ""
    for attempt in range(RPC_ATTEMPTS):
        request = urllib.request.Request(
            endpoint,
            data=body,
            headers={"Content-Type": "application/json", "User-Agent": USER_AGENT},
        )
        try:
            with urllib.request.urlopen(request, timeout=RPC_TIMEOUT_SECONDS) as response:
                answers = json.load(response)
            if not isinstance(answers, list) or len(answers) != len(calls):
                raise UpdateError(f"{endpoint} answered a batch of {len(calls)} with {answers!r:.200}")
            by_id = {answer.get("id"): answer for answer in answers}
            results = []
            for i in range(len(calls)):
                answer = by_id.get(i, {})
                if "result" not in answer:
                    raise UpdateError(f"{endpoint} {calls[i]}: {answer.get('error')}")
                results.append(answer["result"])
            return results
        except (OSError, ValueError, UpdateError) as error:
            last_error = str(error)
            time.sleep(2 ** (attempt + 1))
    raise UpdateError(f"{endpoint}: {last_error}")


def head(endpoint: str) -> int:
    return int(rpc(endpoint, [("eth_blockNumber", [])])[0], 16)


def block_times(endpoint: str, blocks: list[int]) -> dict[int, int]:
    def fetch(batch: list[int]) -> dict[int, int]:
        results = rpc(endpoint, [("eth_getBlockByNumber", [hex(block), False]) for block in batch])
        times = {}
        for block, result in zip(batch, results):
            if result is None or int(result["number"], 16) != block:
                raise UpdateError(f"{endpoint} returned {result and result.get('number')} for block {block}")
            times[block] = int(result["timestamp"], 16)
        return times

    size = BATCH.get(urllib.parse.urlsplit(endpoint).hostname, DEFAULT_BATCH)
    batches = [blocks[offset : offset + size] for offset in range(0, len(blocks), size)]
    times: dict[int, int] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=WORKERS) as pool:
        for batch_times in pool.map(fetch, batches):
            times.update(batch_times)
    return times


def agreed_times(endpoints: tuple[str, str], indices: list[int]) -> dict[int, int]:
    """Fetch each index from both endpoints and require identical times."""
    blocks = [block_at(index) for index in indices]
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(endpoints)) as pool:
        first, second = pool.map(lambda endpoint: block_times(endpoint, blocks), endpoints)
    for block in blocks:
        if first[block] != second[block]:
            raise UpdateError(
                f"endpoints disagree at block {block}: {endpoints[0]}={first[block]} {endpoints[1]}={second[block]}"
            )
    return {index: first[block_at(index)] for index in indices}


def update(endpoints: tuple[str, str]) -> None:
    times = read_table()
    if times:
        validate(times, int(time.time()))

    heads = [head(endpoint) for endpoint in endpoints]
    last_index = (min(heads) - REORG_MARGIN - START_BLOCK) // STEP
    new_indices = list(range(len(times), last_index + 1))

    recheck = list(range(max(0, len(times) - RECHECK_EXISTING), len(times)))
    fetched = agreed_times(endpoints, recheck + new_indices)
    for index in recheck:
        if fetched[index] != times[index]:
            raise UpdateError(
                f"checked-in time at block {block_at(index)} is {times[index]}, "
                f"but both endpoints report {fetched[index]}"
            )

    if not new_indices:
        print(f"up to date: last block {block_at(len(times) - 1)}, heads {heads}")
        return

    updated = times + [fetched[index] for index in new_indices]
    validate(updated, int(time.time()))
    DATA_FILE.write_text(render_table(updated))
    old_last = block_at(len(times) - 1) if times else None
    print(
        f"added {len(new_indices)} entries: last block {old_last} -> "
        f"{block_at(len(updated) - 1)} (agreed by {endpoints[0]} and {endpoints[1]})"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="validate the file without network access")
    parser.add_argument(
        "--endpoint",
        action="append",
        help="Ethereum mainnet JSON-RPC URL; pass exactly twice to override the defaults",
    )
    args = parser.parse_args()
    try:
        if args.check:
            times = read_table()
            validate(times, int(time.time()))
            if DATA_FILE.read_text() != render_table(times):
                raise UpdateError(f"{DATA_FILE} is not in canonical generated form")
            print(f"ok: {len(times)} entries through block {block_at(len(times) - 1)}")
            return 0
        endpoints = tuple(args.endpoint or DEFAULT_ENDPOINTS)
        if len(endpoints) != 2 or endpoints[0] == endpoints[1]:
            raise UpdateError("exactly two distinct endpoints are required")
        update(endpoints)  # type: ignore[arg-type]
        return 0
    except UpdateError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
