#!/usr/bin/env bash
# Selects the identity the macOS app builds with (AGENTS.md, "Desktop
# identity"). It writes or removes macos/Runner/Configs/FlavorOverrides.xcconfig,
# the ignored file AppInfo.xcconfig includes, so the choice lasts until it is
# cleared. Without the file the build keeps upstream's Vizor identity.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OVERRIDES_PATH="$ROOT_DIR/macos/Runner/Configs/FlavorOverrides.xcconfig"
# The same rule as VIZOR_APPLICATION_ID in android/app/build.gradle.kts.
APPLICATION_ID_PATTERN='^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$'

usage() {
  cat <<USAGE
Usage: scripts/macos-identity.sh <application-id> [--release] | --clear | --show

  com.veylor.desktop          Veylor (mainnet)
  com.veylor.desktop.testnet  Veylor Testnet (build with
                              --dart-define=ZCASH_DEFAULT_NETWORK=test)
  --release                   Release builds sign for direct distribution
                              (Developer ID and the "Veylor Desktop Developer
                              ID" profile) and compile Sparkle in. Only
                              com.veylor.desktop has that profile.
                              scripts/release-veylor-macos.sh selects it for
                              the length of a release.
  --clear                     Back to upstream's identity (com.keplr.vizor)
  --show                      Print the selected identity

Then build as usual, for example:
  scripts/macos-identity.sh com.veylor.desktop && fvm flutter run -d macos
USAGE
}

show() {
  if [[ -f "$OVERRIDES_PATH" ]]; then
    local id
    id="$(sed -n 's/^PRODUCT_BUNDLE_IDENTIFIER = //p' "$OVERRIDES_PATH")"
    if grep -q '^CODE_SIGN_IDENTITY\[config=Release\] = Developer ID Application$' "$OVERRIDES_PATH"; then
      echo "$id (Release signs with Developer ID)"
    else
      echo "$id"
    fi
  else
    echo "com.keplr.vizor (upstream default)"
  fi
}

APPLICATION_ID=""
RELEASE_SIGNING=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    --clear)
      [[ $# -eq 1 && -z "$APPLICATION_ID" ]] || { usage >&2; exit 2; }
      rm -f "$OVERRIDES_PATH"
      echo "macOS identity: com.keplr.vizor (upstream default)"
      exit 0
      ;;
    --show)
      [[ $# -eq 1 && -z "$APPLICATION_ID" ]] || { usage >&2; exit 2; }
      show
      exit 0
      ;;
    --release)
      RELEASE_SIGNING=true
      shift
      ;;
    -*)
      usage >&2
      exit 2
      ;;
    *)
      [[ -z "$APPLICATION_ID" ]] || { usage >&2; exit 2; }
      APPLICATION_ID="$1"
      shift
      ;;
  esac
done

if [[ -z "$APPLICATION_ID" ]]; then
  usage >&2
  exit 2
fi

if [[ ! "$APPLICATION_ID" =~ $APPLICATION_ID_PATTERN ]]; then
  echo "The application id must be a package name such as com.veylor.desktop, not '$APPLICATION_ID'." >&2
  exit 1
fi

# Veylor builds sign with Zapp LLC's team: its Apple Development certificate
# and the app's Mac development profile, which lists the Macs it runs on, or,
# for a release, its Developer ID certificate and the app's Developer ID
# profile (AGENTS.md, "Desktop identity").
VEYLOR_TEAM="63UVRFCV97"
RELEASE_PROFILE_NAME=""
case "$APPLICATION_ID" in
  com.veylor.desktop)
    PRODUCT_NAME="Veylor"
    PROFILE_NAME="Veylor Desktop Mac Development"
    RELEASE_PROFILE_NAME="Veylor Desktop Developer ID"
    ;;
  com.veylor.desktop.testnet)
    PRODUCT_NAME="Veylor Testnet"
    PROFILE_NAME="Veylor Desktop Testnet Mac Development"
    ;;
  *)
    echo "No macOS identity is defined for '$APPLICATION_ID'. Use com.veylor.desktop or com.veylor.desktop.testnet." >&2
    exit 1
    ;;
esac

if [[ "$RELEASE_SIGNING" == true && -z "$RELEASE_PROFILE_NAME" ]]; then
  echo "'$APPLICATION_ID' has no Developer ID profile, so it has no release signing." >&2
  exit 1
fi

if [[ "$RELEASE_SIGNING" == true ]]; then
  RELEASE_IDENTITY="Developer ID Application"
  RELEASE_PROFILE="$RELEASE_PROFILE_NAME"
else
  RELEASE_IDENTITY="Apple Development"
  RELEASE_PROFILE="$PROFILE_NAME"
fi

{
  cat <<EOF_OVERRIDES
// Generated by scripts/macos-identity.sh; do not commit.
PRODUCT_NAME = $PRODUCT_NAME
PRODUCT_BUNDLE_IDENTIFIER = $APPLICATION_ID
MACOS_APP_ICON_FILE = VeylorAppIcon
PRODUCT_COPYRIGHT = Copyright © 2026 Zapp LLC. All rights reserved.
DEVELOPMENT_TEAM = $VEYLOR_TEAM
CODE_SIGN_STYLE = Manual
CODE_SIGN_STYLE[config=Release] = Manual
CODE_SIGN_IDENTITY = Apple Development
CODE_SIGN_IDENTITY[config=Release] = $RELEASE_IDENTITY
PROVISIONING_PROFILE_SPECIFIER = $PROFILE_NAME
PROVISIONING_PROFILE_SPECIFIER[config=Release] = $RELEASE_PROFILE
EOF_OVERRIDES
  if [[ "$RELEASE_SIGNING" == true ]]; then
    # shellcheck disable=SC2016 # $(inherited) is Xcode's, not the shell's.
    echo 'SWIFT_ACTIVE_COMPILATION_CONDITIONS[config=Release] = $(inherited) SPARKLE_ENABLED'
  fi
} > "$OVERRIDES_PATH"

if [[ "$RELEASE_SIGNING" == true ]]; then
  echo "macOS identity: $APPLICATION_ID ($PRODUCT_NAME, Release signs with Developer ID)"
else
  echo "macOS identity: $APPLICATION_ID ($PRODUCT_NAME)"
fi
